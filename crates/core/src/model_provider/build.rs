//! Builds the maker snapshot from models.dev's `api.json`.

use std::fmt::Write as _;

use serde_json::Value;

use super::family;

/// Makers peektrace shows a logo for, in match priority: a model id two
/// makers list goes to the first. Each has `assets/logos/providers/<id>.svg`.
pub const MAKERS: [&str; 13] = [
    "anthropic",
    "openai",
    "google",
    "xai",
    "zai",
    "moonshotai",
    "alibaba",
    "deepseek",
    "mistral",
    "minimax",
    "meta",
    "nvidia",
    "cohere",
];

/// Display names models.dev spells for its site, not for a badge.
const NAMES: [(&str, &str); 2] = [("minimax", "MiniMax"), ("nvidia", "NVIDIA")];

const HEAD: &str = "# Model makers from models.dev (MIT): id, name, model ids. Generated by\n\
# `peektrace pricing update --providers`; do not edit.\n";

/// A maker's own model ids: lowercase, without a host's `org/` ids, and
/// without ids whose family belongs to another maker (a host lists those).
fn own_ids(id: &str, models: &serde_json::Map<String, Value>) -> Vec<String> {
    let mut ids: Vec<String> = models
        .keys()
        .map(|m| m.to_ascii_lowercase())
        .filter(|m| !m.contains('/') && !m.contains(char::is_whitespace))
        .filter(|m| family(m).is_none_or(|f| f == id))
        .collect();
    ids.sort();
    ids.dedup();
    ids
}

/// The snapshot text: one tab-separated `id`, `name`, space-separated
/// model ids line per maker, in [`MAKERS`] order.
pub fn providers_snapshot(api_json: &str) -> Result<String, String> {
    let api: Value = serde_json::from_str(api_json).map_err(|e| e.to_string())?;
    let mut taken: Vec<String> = Vec::new();
    let mut out = HEAD.to_owned();
    for id in MAKERS {
        let p = api
            .get(id)
            .ok_or_else(|| format!("no {id} provider in models.dev"))?;
        let name = NAMES
            .iter()
            .find(|(k, _)| *k == id)
            .map(|(_, n)| (*n).to_owned())
            .or_else(|| p.get("name").and_then(Value::as_str).map(str::to_owned))
            .unwrap_or_else(|| id.to_owned());
        let models = p.get("models").and_then(Value::as_object);
        let ids: Vec<String> = models
            .map(|m| own_ids(id, m))
            .unwrap_or_default()
            .into_iter()
            .filter(|m| !taken.contains(m))
            .collect();
        taken.extend(ids.iter().cloned());
        let name = name.replace(['\t', '\n'], " ");
        let _ = writeln!(out, "{id}\t{name}\t{}", ids.join(" "));
    }
    Ok(out)
}
