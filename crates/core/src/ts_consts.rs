//! Writes the constants the inspector shares with core, so the two cannot
//! drift. Run with `UPDATE_TS_TYPES=1` to rewrite the checked-in file.

use serde_json::{Value, json};

use crate::export::ExportFormat;
use crate::memory::types::{MAX_INDEX_BYTES, MAX_INDEX_LINES, MEMORY_TYPES};
use crate::model::Agent;
use crate::sessions::analyze::cat_meta;
use crate::sessions::model::{BudgetKey, EventKind};
use crate::stats::detectors::causes::spec;
use crate::stats::detectors::pairing::RETRY_WINDOW;
use crate::stats::findings::NO_RULE;
use crate::stats::rank::DEFAULT_DRILL_PAGE;
use crate::stats::schema::{CauseId, DETECTOR_VERSION};

const OUT: &str = "../../packages/view-core/src/constants.gen.ts";

const HEADER: &str = "// Generated by crates/core (cargo test -p peektrace-core). Do not edit.\n\
import type { AgentId, BudgetKey, CauseId, CauseKind, EventKind } from \"./api-types.gen\";\n";

/// A record literal whose keys keep their order; values are scalars.
fn ordered(rows: &[(&str, Vec<(&str, Value)>)]) -> String {
    let rows: Vec<String> = rows
        .iter()
        .map(|(key, fields)| {
            let fields: Vec<String> = fields
                .iter()
                .map(|(name, v)| format!("    {name}: {v}"))
                .collect();
            format!("  {}: {{\n{}\n  }}", json!(key), fields.join(",\n"))
        })
        .collect();
    format!("{{\n{}\n}}", rows.join(",\n"))
}

/// `export const NAME = <literal> as const;`, with an optional `satisfies`.
fn constant(doc: &str, name: &str, literal: &str, satisfies: Option<&str>) -> String {
    let tail = satisfies.map_or_else(String::new, |t| format!(" satisfies {t}"));
    format!("\n/** {doc} */\nexport const {name} = {literal} as const{tail};\n")
}

fn json_lit(v: &Value) -> String {
    serde_json::to_string_pretty(v).expect("constant json")
}

/// A whole number as an integer literal (`2`, not `2.0`).
#[expect(clippy::cast_possible_truncation, reason = "small whole constants")]
fn whole(n: f64) -> String {
    (n as i64).to_string()
}

fn cat_meta_lit() -> String {
    let rows: Vec<_> = BudgetKey::ALL
        .into_iter()
        .map(|key| {
            let m = cat_meta(key);
            let mut fields = vec![
                ("label", json!(m.label)),
                ("short", json!(m.short)),
                ("color", json!(m.color)),
                ("estimated", json!(true)),
            ];
            if let Some(note) = m.note {
                fields.push(("note", json!(note)));
            }
            (key.as_str(), fields)
        })
        .collect();
    ordered(&rows)
}

fn causes_lit() -> String {
    let rows: Vec<_> = CauseId::ALL
        .iter()
        .map(|&id| {
            let s = spec(id);
            let fields = vec![
                ("kind", json!(s.kind.as_str())),
                ("label", json!(s.label)),
                ("fix", json!(s.fix)),
                ("failing", json!(s.failing)),
            ];
            (id.as_str(), fields)
        })
        .collect();
    ordered(&rows)
}

fn generated() -> String {
    let agents: Vec<&str> = Agent::ALL.iter().map(|a| a.as_str()).collect();
    let kinds: Vec<&str> = EventKind::ALL.iter().map(|k| k.as_str()).collect();
    let formats: Vec<&str> = ExportFormat::ALL.iter().map(|f| f.as_str()).collect();
    [
        HEADER.to_owned(),
        constant(
            "Every agent id, in matrix order.",
            "AGENT_IDS",
            &json_lit(&json!(agents)),
            Some("readonly AgentId[]"),
        ),
        constant(
            "Every timeline event kind.",
            "EVENT_KINDS",
            &json_lit(&json!(kinds)),
            Some("readonly EventKind[]"),
        ),
        constant(
            "Documented frontmatter `type` values.",
            "MEMORY_TYPES",
            &json_lit(&json!(MEMORY_TYPES)),
            None,
        ),
        constant(
            "Lines of MEMORY.md Claude loads; later lines are invisible.",
            "MAX_INDEX_LINES",
            &MAX_INDEX_LINES.to_string(),
            None,
        ),
        constant(
            "Bytes of MEMORY.md Claude loads (25 KB).",
            "MAX_INDEX_BYTES",
            &MAX_INDEX_BYTES.to_string(),
            None,
        ),
        constant(
            "Label, short name and colour of each budget category, in stack order.",
            "CAT_META",
            &cat_meta_lit(),
            Some(
                "Record<BudgetKey, { readonly label: string; readonly short: string; readonly color: string; readonly estimated: boolean; readonly note?: string }>",
            ),
        ),
        constant(
            "Where each named cause's fix lives, its label and fix line.",
            "CAUSES",
            &causes_lit(),
            Some(
                "Record<CauseId, { readonly kind: CauseKind; readonly label: string; readonly fix: string | null; readonly failing: boolean }>",
            ),
        ),
        constant(
            "Calls after a failure within which a similar success counts as its retry.",
            "RETRY_WINDOW",
            &whole(RETRY_WINDOW),
            None,
        ),
        constant(
            "Bumped when a detector's rule changes.",
            "DETECTOR_VERSION",
            &whole(DETECTOR_VERSION),
            None,
        ),
        constant(
            "Calls a drill page holds unless the caller asks for another size.",
            "DEFAULT_DRILL_PAGE",
            &DEFAULT_DRILL_PAGE.to_string(),
            None,
        ),
        constant(
            "Session export formats.",
            "EXPORT_FORMATS",
            &json_lit(&json!(formats)),
            None,
        ),
        constant(
            "The fix text of a cause with no rule.",
            "NO_RULE",
            &json_lit(&json!(NO_RULE)),
            None,
        ),
    ]
    .concat()
}

#[test]
fn ts_constants_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(OUT);
    let want = generated();
    if std::env::var_os("UPDATE_TS_TYPES").is_some() {
        std::fs::write(&path, &want).expect("write generated constants");
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale: run UPDATE_TS_TYPES=1 cargo test -p peektrace-core --lib ts_consts",
        path.display()
    );
}
