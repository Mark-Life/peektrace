//! Writes the TS declarations the inspector imports. Run with
//! `UPDATE_TS_TYPES=1` to rewrite the checked-in file.

use ts_rs::{Config, TS};

use super::*;

const OUT: &str = "../../apps/inspector/src/lib/api-types.gen.ts";

const HEADER: &str = "// Generated by crates/protocol (cargo test -p peektrace-protocol). Do not edit.\n\
import type { AnalyzedSession, ParsedSession, SessionHeader } from \"@workspace/core/services/sessions/schema\";\n\n\
export type { AnalyzedSession, ParsedSession, SessionHeader };\n";

fn decl<T: TS>(cfg: &Config) -> String {
    format!("\nexport {}\n", T::decl(cfg))
}

fn generated() -> String {
    let cfg = Config::new().with_large_int("number");
    [
        HEADER.to_owned(),
        decl::<AgentId>(&cfg),
        decl::<SupportLevel>(&cfg),
        decl::<CapabilitySupport>(&cfg),
        decl::<PerAgentSupport>(&cfg),
        decl::<Capability>(&cfg),
        decl::<ScannedRoot>(&cfg),
        decl::<AgentScan>(&cfg),
        decl::<ServerInfo>(&cfg),
        decl::<RootEntry>(&cfg),
        decl::<PeektraceSettings>(&cfg),
        decl::<SettingsResult>(&cfg),
        decl::<SettingsUpdate>(&cfg),
        decl::<WatchVersions>(&cfg),
        decl::<UnreadableSession>(&cfg),
        decl::<SessionListing>(&cfg),
        decl::<SessionsQuery>(&cfg),
        decl::<SessionQuery>(&cfg),
        decl::<AnalysisQuery>(&cfg),
        decl::<FileChangeReason>(&cfg),
        decl::<NotPortedFeature>(&cfg),
        decl::<ApiError>(&cfg),
        decl::<ApiErrorBody>(&cfg),
    ]
    .concat()
}

#[test]
fn ts_types_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(OUT);
    let want = generated();
    if std::env::var_os("UPDATE_TS_TYPES").is_some() {
        std::fs::write(&path, &want).expect("write generated types");
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale: run UPDATE_TS_TYPES=1 cargo test -p peektrace-protocol",
        path.display()
    );
}
