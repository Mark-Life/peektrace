#[test]
fn ts_types_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(OUT);
    let want = generated();
    if std::env::var_os("UPDATE_TS_TYPES").is_some() {
        std::fs::write(&path, &want).expect("write generated types");
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale: run UPDATE_TS_TYPES=1 cargo test -p peektrace-protocol",
        path.display()
    );
}
