//! Writes the TS declarations the inspector imports. Run with
//! `UPDATE_TS_TYPES=1` to rewrite the checked-in file.

use ts_rs::{Config, TS};

use super::*;

const OUT: &str = "../../apps/inspector/src/lib/api-types.gen.ts";

const HEADER: &str = "// Generated by crates/protocol (cargo test -p peektrace-protocol). Do not edit.\n\
import type { AnalyzedSession, ParsedSession, SessionHeader, TimelineEvent } from \"@workspace/core/services/sessions/schema\";\n\n\
export type { AnalyzedSession, ParsedSession, SessionHeader };\n\n\
/** `GET /api/sessions/{id}/summary`: the analysis without its arrays, plus the parts' hashes. */\n\
export type SessionSummary = Omit<AnalyzedSession, \"events\" | \"turns\" | \"snapshots\"> & { readonly history: SummaryHistory };\n\n\
/** One history index row: an event without its text, plus its turn, body length (UTF-16) and the first position with the same body. */\n\
export type HistoryRow = Omit<TimelineEvent, \"body\" | \"preview\" | \"requestId\" | \"ts\" | \"contextEdit\"> & { readonly contextEdit?: Omit<NonNullable<TimelineEvent[\"contextEdit\"]>, \"original\">; readonly turn: number; readonly bodyLen: number; readonly bodyId: number };\n\n\
/** `GET /api/sessions/{id}/history`. */\n\
export type HistoryPage = HistoryPageMeta & { readonly events: readonly TimelineEvent[] };\n\n\
/** `GET /api/sessions/{id}/history/index`. */\n\
export type HistoryIndex = HistoryIndexMeta & { readonly rows: readonly HistoryRow[] };\n";

fn decl<T: TS>(cfg: &Config) -> String {
    format!("\nexport {}\n", T::decl(cfg))
}

